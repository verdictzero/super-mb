# Cuts the head out of a green-screen portrait: chroma key + soft oval around the head, with
# green spill removed from the edge. Usage: python3 scripts/make-head.py photo.jpg
import sys, base64, io
import numpy as np
from PIL import Image, ImageFilter

src = Image.open(sys.argv[1]).convert('RGB')
a = np.asarray(src).astype(np.float32)
r, g, b = a[..., 0], a[..., 1], a[..., 2]
# how green-screen a pixel is: green well above both other channels
green = g - np.maximum(r, b)
key = np.clip((green - 18) / 40, 0, 1)                       # 1 = background
H, W = green.shape
yy, xx = np.mgrid[0:H, 0:W]
# oval that takes in the head, ears and beard but not the collar and shoulders
cx, cy, rx, ry = 0.487 * W, 0.425 * H, 0.275 * W, 0.335 * H
d = np.sqrt(((xx - cx) / rx) ** 2 + ((yy - cy) / ry) ** 2)
oval = np.clip((1.0 - d) / 0.035, 0, 1)
alpha = (1 - key) * oval
spill = np.clip(g - np.maximum(r, b), 0, None) * np.clip(1.4 - alpha, 0, 1)   # pull green out of soft edges
g2 = g - spill
out = np.dstack([r, g2, b, alpha * 255]).clip(0, 255).astype(np.uint8)
img = Image.fromarray(out, 'RGBA')
box = img.getbbox()
img = img.crop(box)
side = max(img.size)
sq = Image.new('RGBA', (side, side), (0, 0, 0, 0))
sq.paste(img, ((side - img.size[0]) // 2, (side - img.size[1]) // 2))
sq = sq.resize((384, 384), Image.LANCZOS)
sq.save('assets/hero-head.png', optimize=True)
buf = io.BytesIO(); sq.save(buf, 'PNG', optimize=True)
open('src/web/head.js', 'w').write('// Generated by scripts/make-head.py: the player\'s head, cut out of a green-screen photo (384px RGBA PNG).\nexport const HEAD = "data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode() + '";\n')
print('head', sq.size, len(buf.getvalue()), 'bytes')
# preview on a checker so the cut can be inspected
chk = Image.new('RGBA', (384, 384), (60, 60, 90, 255))
for y in range(0, 384, 32):
    for x in range(0, 384, 32):
        if (x // 32 + y // 32) % 2: chk.paste((200, 80, 160, 255), (x, y, x + 32, y + 32))
chk.alpha_composite(sq); chk.save(sys.argv[2] if len(sys.argv) > 2 else '/dev/null', 'PNG')
